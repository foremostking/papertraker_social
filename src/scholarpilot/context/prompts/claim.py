CLAIM_CALIBRATION_PROMPT = """## 任务：校准结论与证据的匹配关系

### 结论句
{claim_text}

### 结论类型
{claim_type}

### 该结论所在章节全文（用于上下文）
{section_context}

### 引用的参考文献详情
{references_detail}

### 证据矩阵中的相关论点-证据映射（如有）
{evidence_mapping}

### 请判断结论是否有充分证据支撑

请以JSON格式输出：

```json
{{
  "support_status": "supported|overreach|unsupported|partial",
  "issue_type": "overreach|unsupported|partial_support|mismatch|exaggeration|null",
  "evidence_basis": "证据基础描述（说明判断依据）",
  "recommendation": "修改建议（如需修改）"
}}
```

### 判断标准
- **supported**：结论有充分引用支撑且证据强度与结论类型匹配
- **overreach**：数据/证据只支撑相关性，但结论表述为因果性（最常见的越界）
- **unsupported**：结论无任何引用支撑
- **partial**：引用存在但证据强度不足以完全支撑结论

### issue_type 对应关系
- overreach → 结论越界（相关性→因果性）
- unsupported → 无引用支撑
- partial_support → 部分支撑
- mismatch → 图文/数据不匹配
- exaggeration → 夸大表述
- null → 无问题（supported时）

### 关键判断规则
1. 因果性结论（causal）必须有因果识别策略支撑（如IV、DID、RD、自然实验）
2. 如果研究仅做了OLS回归，结论不得使用"导致""促进"等因果性表述
3. 描述性统计不得推出因果性结论
4. 规范性结论需要基于实证证据，不能凭空建议

### 重要的上下文判断
- **研究设计章节**中描述方法论时使用因果动词（"采用固定效应模型识别因果关系"）不算越界
- **文献综述章节**中转述他人研究结论（"张三（2024）发现数字化转型促进创新"）不算越界
- **理论假设章节**中提出假设（"假设1：数字化转型促进企业创新"）不算越界
- 只有在**实证结果章节**和**结论章节**中，当数据/证据仅支撑相关性但结论表述为因果性时，才算越界
- 如果结论句已有引用支撑（如"研究表明…"），且引用文献使用了因果识别策略，则标记为 supported
- **面板固定效应模型**（Fixed Effects）可以控制不可观测的个体异质性，在一定程度上识别因果关系，使用"促进""抑制"等因果性表述不算越界
- **双重差分法**（DID）、**工具变量法**（IV）、**断点回归**（RD）、**自然实验**都是有效的因果识别策略
- 如果研究设计章节明确说明了使用固定效应模型，实证结果章节中使用"促进""推动"等表述不算越界
- 文献综述中转述他人结论时（如"张三（2024）研究发现..."），无论原文使用何种因果识别策略，都不算越界
- 政策建议章节中的规范性表述（"企业应该..."、"政府应当..."）不需要引用支撑，不算越界
- **关键规则**：如果结论句本身已包含作者（年份）格式的内联引用（如"张三（2024）发现..."、"Smith et al. (2023) showed that..."），则不应标记为 unsupported，至少应标记为 partial 或 supported
- 如果结论句包含"研究表明""现有文献发现"等表述且后文有引用，不算 unsupported
- 如果结论句引用了 hash ID 格式的文献（如 eda77b642991），说明有文献支撑，不算 unsupported
- 只有结论句完全没有任何引用标记（既无作者年份，也无"研究表明"等引用线索）时，才标记为 unsupported
- **引用线索检测**：如果参考文献详情中包含"引用线索检测"部分，说明结论句已包含"研究表明""回归结果显示"等引用/数据线索，不应标记为 unsupported
- **数据支撑判断**：如果结论句包含"回归结果显示""实证结果表明"等表述，说明有数据支撑，应标记为 supported 或 partial（视证据强度而定）
- **理论假设判断**：理论假设（"假设1：..."）不需要引用支撑，应标记为 supported（假设本身是理论推导的产物）
- **文献综述转述规则（最重要）**：在文献综述章节中，如果结论句包含内联引用（如"张三（2024）发现...""Smith et al. (2023) showed that..."），且该结论是对他人研究的转述，应标记为 supported，而非 partial。文献综述的本质就是总结和转述他人研究，不需要验证原文是否使用了因果识别策略
- **章节类型感知**：
  - 文献综述章节：转述他人结论有引用支撑即可，标记为 supported
  - 研究设计章节：描述方法论使用因果动词不算越界，标记为 supported
  - 理论假设章节：假设本身是理论推导产物，标记为 supported
  - 实证结果章节：需要数据支撑，如结论无数据支撑则标记为 unsupported 或 partial
  - 结论与政策建议章节：政策建议不需要引用支撑，标记为 supported
- **partial 的使用标准**：只有当结论句的表述明显超出了引用文献的支撑范围时，才标记为 partial。例如结论说"A导致B"，但引用的文献只研究了"A与B的相关性"。如果引用文献的结论与结论句表述一致，应标记为 supported
"""

