from __future__ import annotations

# ===== 选题细化 =====

TOPIC_REFINEMENT_PROMPT = """## 任务：将宽泛选题细化为可操作的研究问题

你是学术研究助手，请将用户提供的宽泛选题细化为3-5个具体、可操作的研究方向。
借鉴 DeepSeek 五步法的"边界锚定"思路，通过提取核心关键词明确研究边界。

### 输入信息

**初始选题描述**：{initial_topic}

**学科领域**：{discipline}

**当前研究热点**：
{research_hotspots}

---

## 工作流程

### 第一步：边界锚定

1. 从初始选题中提取 4-8 字的核心关键词（不少于3个，不多于6个）。
   - 去掉常见学术后缀（研究、分析、探讨、实证、效应、影响等）
   - 去掉前缀（如"中国"等地域限定词，若非核心要素）
   - 按"的"分割，取长度适中（4-10字）的核心分句
2. 基于核心关键词明确研究边界：
   - **对象边界**：研究什么主体（如地方政府、企业、农户）
   - **内容边界**：研究什么方面（如债务风险、创新效率）
   - **方法边界**：采用什么研究路径（实证/理论/案例）
   - **地域边界**：研究的地域范围（全国/省份/地级市）
   - **时间边界**：研究的时间跨度

### 第二步：生成细化方向

基于锚定的边界和当前研究热点，生成3-5个细化研究方向。每个方向必须：
- 聚焦一个明确的研究问题（可在一篇论文中回答）
- 与当前研究热点有明确关联
- 具有可操作性（能在合理时间内完成）
- 避免与现有研究简单重复

---

## 输出格式

请按以下结构输出，每个细化方向包含4个要素：

```
【边界锚定结果】
核心关键词：关键词A、关键词B、关键词C……
研究边界：
  - 对象边界：……
  - 内容边界：……
  - 方法边界：……
  - 地域边界：……
  - 时间边界：……

【细化方向 1】
研究问题：用一个问句表述，如"XX对YY的影响机制是什么？"
研究对象：具体的研究对象和样本范围
研究视角：采用什么理论视角或分析角度
预期贡献：本研究可能的理论贡献或实践价值（1-2句话）
关联热点：与当前哪个研究热点相关

【细化方向 2】
研究问题：……
研究对象：……
研究视角：……
预期贡献：……
关联热点：……

……（共3-5个方向）

【推荐排序】
按可行性和创新性综合排序，说明推荐理由。
```

### 输出要求
1. 每个研究问题必须是**可在一篇论文中回答的具体问题**，不能过于宽泛
2. 研究对象要明确到可操作层面（如"2015-2024年A股上市公司"而非"企业"）
3. 研究视角要具体（如"从资源禀赋视角"而非"多角度"）
4. 预期贡献要诚实，区分理论贡献和实践价值
5. 用中文撰写，学术规范语言
"""

