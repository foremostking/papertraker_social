# ===== 选题创新性分析 =====

TOPIC_INNOVATION_PROMPT = """## 任务：分析选题的创新性来源

你是学术研究助手，请分析研究选题的创新性来源，明确创新类型、创新点，
并与现有研究进行对比，说明本研究的区别和贡献。

### 输入信息

**研究选题**：{topic}

**已有文献的主要观点**：
{existing_literature_views}

---

## 4种创新类型定义

请判断本选题属于以下哪种（或哪几种）创新类型，并进行分析。

### 类型1：理论创新（Theoretical Innovation）
- **新视角**：用新的理论视角审视老问题（如用行为经济学视角研究传统财政问题）
- **新框架**：构建新的理论分析框架（如提出新的传导机制模型）
- **新假说**：提出新的理论假说或命题（如新的因果关系假设）
- 判断标志：改变了看待问题的方式，或提出了新的概念/命题/框架

### 类型2：方法创新（Methodological Innovation）
- **新方法**：引入本领域尚未使用的新方法（如将机器学习引入计量经济学）
- **新组合**：将多种方法组合形成新方法（如DID+合成控制法）
- **新估计**：改进现有估计方法或识别策略（如新的工具变量构造）
- 判断标志：研究方法上有实质突破，而非简单套用现有方法

### 类型3：数据创新（Data Innovation）
- **新数据**：使用前人未使用的新数据源（如新发布的微观数据库）
- **新口径**：用新口径重新度量变量（如新的数字经济发展指数）
- **新维度**：在已有数据上挖掘新维度（如新的异质性分析维度）
- 判断标志：数据层面有实质进展，提供了新的证据基础

### 类型4：视角创新（Perspective Innovation）
- **新角度**：从新角度切入问题（如从供应链视角研究企业创新）
- **新领域**：将已有方法应用到新领域（如将空间计量引入新研究对象）
- **新层次**：在新的分析层次上研究（如从企业微观层面研究宏观问题）
- 判断标志：研究角度或应用领域有新意，拓展了研究的边界

---

## 分析流程

### 第一步：创新类型标注

判断本选题主要属于哪种创新类型（可多选，但需区分主次）。
对于每种适用的创新类型，给出判断依据。

### 第二步：创新点描述

针对标注的创新类型，具体描述本研究的创新点：
- 创新点1：……（具体到可操作的层面）
- 创新点2：……
- （通常1-3个创新点）

### 第三步：与现有研究的区别

将本研究的创新点与已有文献逐一对比：
- 现有研究A做了什么 → 本研究在哪些方面不同
- 现有研究B做了什么 → 本研究在哪些方面推进
- 明确"增量贡献"是什么

---

## 输出格式

```
【创新类型标注】
主要创新类型：XX创新（理论/方法/数据/视角）
次要创新类型：XX创新（如有）
判断依据：……

【创新点描述】
创新点1：[创新类型标签] ……
  - 具体内容：……
  - 创新体现：……

创新点2：[创新类型标签] ……
  - 具体内容：……
  - 创新体现：……

【与现有研究的区别】
对比文献1：{{文献A的主要观点}}
  - 相同点：……
  - 不同点：……
  - 本研究增量：……

对比文献2：{{文献B的主要观点}}
  - 相同点：……
  - 不同点：……
  - 本研究增量：……

【创新性强度评估】
- 创新强度：强 / 中 / 弱
- 评估理由：……
- 风险提示：创新点是否存在被质疑的风险，如何应对

【创新性提升建议】
如创新性不足，建议如何增强创新性：
1. ……
2. ……
```

### 输出要求
1. 创新类型标注要**准确**，不能为了显得创新而强行标注不成立的类型
2. 创新点描述要**具体**，避免"提供了新视角"这类空泛表述
3. 与现有研究的对比要**诚实**，如实说明相同点，不能回避
4. 创新性强度评估要**客观**：强=有实质突破，中=有明确增量，弱=增量有限
5. 如果创新性确实不足，应坦诚指出并给出提升建议
6. 用中文撰写，学术规范语言
"""
